class Label(Row):
    """Engineered supervision, kept separate from facts so leakage can be checked mechanically."""

    TABLE: ClassVar[str] = "label"
    KEY: ClassVar[str] = "label_id"
    label_id: str
    task: str
    entity_type: str  # shipment | stop | route | zone_window
    entity_id: str
    value: float
    as_of_ts: pd.Timestamp | None = None  # prediction time; features may use ts <= as_of_ts only
    as_of_day_index: int | None = None  # same, for sources without a year
    available_at_ts: pd.Timestamp | None = None  # when the outcome becomes knowable
    available_at_day_index: int | None = None
    definition: str  # human-readable, versioned definition ("late = delivered_ts > promised_end_ts; v1")


TABLES: dict[str, type[Row]] = {
    m.TABLE: m
    for m in (Node, Courier, Route, Stop, Shipment, Event, Attempt, AddressContext, RecipientContext, NodeState,
              CorridorState, Exception_, Incident, IncidentMember, Action, Decision, Outcome, Label)
}


# ─── Validation ──────────────────────────────────────────────────────────────────────────────────
class SchemaViolation(ValueError):
    pass


def _enum_values(annotation: Any) -> set[str] | None:
    for arg in getattr(annotation, "__args__", (annotation,)):
        if isinstance(arg, type) and issubclass(arg, StrEnum):
            return {m.value for m in arg}
    return None


def validate_frame(table: str, df: pd.DataFrame, provides: set[str] | None = None) -> None:
    """Structural validation of a table DataFrame. Raises SchemaViolation with every problem found.

    Checks: unknown/missing columns, key uniqueness, enum domains, provenance rules (synthetic and demo
    rows must carry scenario_id), the adapter's `provides` contract (columns outside it must be null), and
    for labels the leakage rule available_at > as_of.
    """
    model = TABLES[table]
    fields = model.model_fields
    problems: list[str] = []

    unknown = set(df.columns) - set(fields)
    if unknown:
        problems.append(f"unknown columns {sorted(unknown)}")
    required = {n for n, f in fields.items() if f.is_required()}
    missing = required - set(df.columns)
    if missing:
        problems.append(f"missing required columns {sorted(missing)}")
    if problems:
        raise SchemaViolation(f"{table}: " + "; ".join(problems))

    if df[model.KEY].duplicated().any():
        problems.append(f"duplicate {model.KEY}")
    for name in required:
        if df[name].isna().any():
            problems.append(f"nulls in required column {name}")
    for name, f in fields.items():
        if name not in df.columns:
            continue
        dom = _enum_values(f.annotation)
        if dom is not None:
            bad = set(df[name].dropna().unique()) - dom
            if bad:
                problems.append(f"{name} has values outside enum: {sorted(map(str, bad))[:5]}")

    origins = df["origin"].astype(str)
    needs_scn = origins.isin([Origin.SYNTHETIC.value, Origin.DEMO.value])
    if needs_scn.any() and df.loc[needs_scn, "scenario_id"].isna().any():
        problems.append("synthetic/demo rows must carry scenario_id")
    if (~needs_scn).any() and df.loc[~needs_scn, "scenario_id"].notna().any():
        problems.append("observed/engineered rows must not carry scenario_id")

    if provides is not None:
        base = set(Row.model_fields) | {model.KEY} | required
        for col in set(df.columns) - base - provides:
            if df[col].notna().any():
                problems.append(f"column {col} filled but not declared in adapter PROVIDES")

    if table == "label":
        has_ts = df["as_of_ts"].notna() & df["available_at_ts"].notna()
        if (df.loc[has_ts, "available_at_ts"] <= df.loc[has_ts, "as_of_ts"]).any():
            problems.append("label available_at_ts must be after as_of_ts")
        has_d = df["as_of_day_index"].notna() & df["available_at_day_index"].notna()
        if (df.loc[has_d, "available_at_day_index"] < df.loc[has_d, "as_of_day_index"]).any():
            problems.append("label available_at_day_index must be >= as_of_day_index")
        if not (has_ts | has_d).all():
            problems.append("every label needs as_of/available_at (timestamp or day index)")

    if table == "action":
        rnd = df["assignment"].astype(str) == AssignmentMechanism.RANDOMIZED.value
        if rnd.any() and df.loc[rnd, "propensity"].isna().any():
            problems.append("RANDOMIZED actions must log propensity")

    if problems:
        raise SchemaViolation(f"{table}: " + "; ".join(problems))


def empty_frame(table: str) -> pd.DataFrame:
    return pd.DataFrame({n: pd.Series(dtype="object") for n in TABLES[table].model_fields})
